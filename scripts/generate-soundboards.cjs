const fs = require('node:fs');
const path = require('node:path');

function discoverSoundboards(assets) {
  const root = path.join(assets, 'raw', 'Soundboards');
  const exists = (relative) => {
    try { return fs.statSync(path.join(assets, relative)).isFile(); }
    catch { return false; }
  };
  const requireFile = (relative) => {
    if (!exists(relative)) throw new Error(`Missing required file: ${relative}`);
    return relative;
  };
  const picture = (name, filename) => {
    const specific = `image/${name}/${filename}`;
    return exists(specific) ? specific : requireFile(`image/Default/${filename}`);
  };
  const folders = fs.readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
  if (!folders.length) throw new Error('No soundboard folders found in raw/Soundboards.');
  return folders.map((name) => {
    const tiles = Array.from({ length: 8 }, (_, index) => {
      const number = String(index + 1).padStart(2, '0');
      return {
        id: `sound-${number}`,
        audio: requireFile(`raw/Soundboards/${name}/Sound-${number}.mp3`),
        image: picture(name, `Pic-${number}.png`),
        pressed: picture(name, `Pic-Pressed-${number}.png`)
      };
    });
    tiles.push({
      id: 'settings', action: 'settings', audio: null,
      image: requireFile('image/settings.png'),
      pressed: requireFile('image/settings-pressed.png')
    });
    return { id: name, name, tiles };
  });
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  try {
    const presets = discoverSoundboards(path.join(root, 'assets', 'bip-6'));
    const source = '// Generated by npm run generate. Edit asset folders, not this file.\n'
      + `export const presets = ${JSON.stringify(presets, null, 2)};\n`;
    fs.writeFileSync(path.join(root, 'utils', 'sounds.js'), source);
    console.log(`Generated ${presets.length} soundboards: ${presets.map((p) => p.name).join(', ')}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { discoverSoundboards };
